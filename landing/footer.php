<script>
    jQuery(function($) {

        let saved = {};
        let timers = {};

        $('#wpforms-31-field_2, #wpforms-8-field_2').on('input', function() {

            let $phoneField = $(this);
            let fieldId = $phoneField.attr('id');
            let phone = $phoneField.val().replace(/\D/g, '');

            let nameField = fieldId === 'wpforms-31-field_2' ?
                $('#wpforms-31-field_1') :
                $('#wpforms-8-field_1');

            clearTimeout(timers[fieldId]);

            if (phone.length === 10 && !saved[fieldId]) {

                timers[fieldId] = setTimeout(function() {

                    $.ajax({
                        url: '<?php echo admin_url('admin-ajax.php'); ?>',
                        type: 'POST',
                        data: {
                            action: 'save_partial_lead',
                            name: nameField.val(), // capture name after 5 seconds
                            phone: phone,
                            page_url: window.location.href
                        },
                        success: function(response) {
                            console.log('Lead saved');
                            saved[fieldId] = true;
                        },
                        error: function() {
                            saved[fieldId] = false;
                        }
                    });

                }, 2000); // wait 2 seconds
            }

            if (phone.length < 10) {
                saved[fieldId] = false;
                clearTimeout(timers[fieldId]);
            }
        });

    });
</script>


