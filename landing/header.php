	<script>
		const canvas = document.getElementById('sparks');
		const ctx = canvas.getContext('2d');
		const box = document.getElementById('tagBx');

		let CX = 0;
		let CY = 0;

		function resize() {
			const r = canvas.getBoundingClientRect();
			canvas.width = r.width;
			canvas.height = r.height;

			CX = canvas.width / 2;
			CY = canvas.height / 2 - 10;
		}

		resize();
		window.addEventListener('resize', resize);

		class Spark {
			constructor(burst) {
				this.reset(burst);
			}

			reset(burst) {
				this.x = CX + (Math.random() - 0.5) * 30;
				this.y = CY + (Math.random() - 0.5) * 60;

				const angle = Math.random() * Math.PI * 2;
				const speed = burst ?
					(2.5 + Math.random() * 3.5) :
					(0.6 + Math.random() * 1.8);

				this.vx = Math.cos(angle) * speed;
				this.vy = Math.sin(angle) * speed - (burst ? 1 : 0.3);

				this.life = burst ?
					(0.6 + Math.random() * 0.4) :
					(0.4 + Math.random() * 0.5);

				this.maxLife = this.life;
				this.size = burst ?
					(1.5 + Math.random() * 2.5) :
					(0.8 + Math.random() * 1.5);

				this.type = Math.random() < 0.4 ? 'star' : 'dot';

				this.rotation = Math.random() * Math.PI * 2;
				this.rotSpeed = (Math.random() - 0.5) * 0.3;

				const hue = 42 + (Math.random() - 0.5) * 20;
				const sat = 90 + Math.random() * 10;
				const lum = 60 + Math.random() * 30;

				this.color = `hsl(${hue}, ${sat}%, ${lum}%)`;

				this.active = true;
			}

			update() {
				this.x += this.vx;
				this.y += this.vy;

				this.vy += 0.04;
				this.vx *= 0.97;

				this.life -= 0.018;
				this.rotation += this.rotSpeed;

				if (this.life <= 0) {
					this.active = false;
				}
			}

			draw(ctx) {
				const alpha = Math.max(0, this.life / this.maxLife);

				ctx.save();
				ctx.globalAlpha = alpha;
				ctx.translate(this.x, this.y);
				ctx.rotate(this.rotation);

				if (this.type === 'star') {
					ctx.fillStyle = this.color;
					ctx.shadowColor = '#F6E208';
					ctx.shadowBlur = 6;

					const s = this.size;

					ctx.beginPath();

					for (let i = 0; i < 4; i++) {
						const a = (i / 4) * Math.PI * 2;
						const r1 = s * 1.5;
						const r2 = s * 0.5;

						ctx.lineTo(
							Math.cos(a) * r1,
							Math.sin(a) * r1
						);

						ctx.lineTo(
							Math.cos(a + Math.PI / 4) * r2,
							Math.sin(a + Math.PI / 4) * r2
						);
					}

					ctx.closePath();
					ctx.fill();

				} else {
					ctx.fillStyle = this.color;
					ctx.shadowColor = '#F6E208';
					ctx.shadowBlur = 8;

					ctx.beginPath();
					ctx.arc(0, 0, this.size, 0, Math.PI * 2);
					ctx.fill();
				}

				ctx.restore();
			}
		}

		let sparks = [];
		let burstTimer = 0;

		function spawnAmbient() {
			if (Math.random() < 0.3) {
				sparks.push(new Spark(false));
			}
		}

		function spawnBurst() {
			for (let i = 0; i < 18; i++) {
				sparks.push(new Spark(true));
			}
		}

		function loop() {
			ctx.clearRect(0, 0, canvas.width, canvas.height);

			spawnAmbient();

			burstTimer++;
			if (burstTimer > 140) {
				spawnBurst();
				burstTimer = 0;
			}

			sparks = sparks.filter(s => s.active);

			for (const s of sparks) {
				s.update();
				s.draw(ctx);
			}

			requestAnimationFrame(loop);
		}

		loop();
	</script>